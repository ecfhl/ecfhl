const fs = require('node:fs'), vm = require('node:vm'), assert = require('node:assert/strict');
const events = {}, storage = {}, columns = ['today', 'tomorrow', 'ec_proj', 'fpts', 'fpts_gp', 'gp'].map(column => ({ dataset: { column }, style: {} }));
const handles = columns.map(col => ({ dataset: { playerResize: col.dataset.column }, setAttribute(key, value) { this[key] = value; }, addEventListener(key, fn) { this[key] = fn; }, removeEventListener() {} }));
const table = { style: {}, querySelectorAll: selector => selector.startsWith('col[') ? columns : handles };
const reset = { addEventListener(_, fn) { this.click = fn; }, removeEventListener() {} };
const scroll = { clientWidth: 350, closest: () => ({ querySelector: () => reset }) };
const window = { innerWidth: 390, addEventListener(key, fn) { events[key] = fn; }, removeEventListener() {} };
let changes = 0;
vm.runInNewContext(fs.readFileSync('public/player-column-resize.js', 'utf8'), { window, localStorage: { getItem: key => storage[key], setItem: (key, value) => storage[key] = value }, document: { documentElement: { classList: { remove() {} } } } });
const dispose = window.EcfhlPlayerColumns.attach(table, scroll, null, () => changes++);
assert.equal(columns[0].style.width, '82px'); assert.equal(columns[4].style.width, '64px'); assert.equal(columns[5].style.width, '56px');
const key = name => ({ key: name, preventDefault() {} });
handles[3].keydown(key('ArrowRight')); assert.equal(columns[3].style.width, '61px');
assert.equal(JSON.parse(storage['ecfhl-player-columns-v2:phone']).fpts, 61);
handles[3].keydown(key('End')); assert.equal(columns[3].style.width, '200px');
reset.click(); assert.equal(columns[3].style.width, '56px');
window.innerWidth = 1200; events.resize(); assert.equal(columns[0].style.width, '100px'); assert.equal(columns[3].style.width, '64px');
handles[3].keydown(key('ArrowLeft')); assert.equal(columns[3].style.width, '59px');
window.innerWidth = 390; events.resize(); assert.equal(columns[3].style.width, '56px');
assert.ok(changes >= 7); dispose();
console.log('Player column checks passed: stat-only mobile/desktop widths, keyboard resizing, limits, reset and independent saved layouts.');
